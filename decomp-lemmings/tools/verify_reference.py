def pe_file_offset(data: bytes, address: int, length: int) -> int:
    """Map a PE32 virtual address to bytes physically backed by a section."""
    if data[:2] != b"MZ":
        raise ValueError("missing DOS header")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("missing PE signature")
    section_count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    if struct.unpack_from("<H", data, pe + 24)[0] != 0x10B:
        raise ValueError("expected a PE32 reference")
    image_base = struct.unpack_from("<I", data, pe + 52)[0]
    rva = address - image_base
    for index in range(section_count):
        entry = pe + 24 + optional_size + index * 40
        _, section_rva, raw_size, raw_offset = struct.unpack_from("<IIII", data, entry + 8)
        displacement = rva - section_rva
        if 0 <= displacement and displacement + length <= raw_size:
            return raw_offset + displacement
    raise ValueError(f"0x{address:08X} range is not backed by file bytes")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exe", type=Path, help="path to installed Lemmings Revolution.exe")
    args = parser.parse_args()

    data = args.exe.read_bytes()
    exe_digest = hashlib.sha256(data).hexdigest()
    if exe_digest != EXE_SHA256:
        parser.error(f"reference executable SHA-256 mismatch: {exe_digest}")

    for address, offset, length, _ in (*FUNCTIONS, *DATA):
        mapped_offset = pe_file_offset(data, address, length)
        if mapped_offset != offset:
            parser.error(f"0x{address:08X} maps to file offset {mapped_offset}, "
                         f"but the recorded offset is {offset}")

    print(f"verified reference executable: {exe_digest}")
    for address, offset, length, expected_digest in FUNCTIONS:
        function = data[offset:offset + length]
        function_digest = hashlib.sha256(function).hexdigest()
        if len(function) != length or function_digest != expected_digest:
            parser.error(f"0x{address:08X} bytes SHA-256 mismatch: {function_digest}")
        print(f"verified 0x{address:08X} ({length} bytes): {function_digest}")
    for address, offset, length, expected_digest in DATA:
        value = data[offset:offset + length]
        digest = hashlib.sha256(value).hexdigest()
        if len(value) != length or digest != expected_digest:
            parser.error(f"0x{address:08X} data SHA-256 mismatch: {digest}")
        print(f"verified data 0x{address:08X} ({length} bytes): {digest}")
    return 0


