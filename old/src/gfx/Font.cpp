const std::uint8_t* glyphBits(std::uint32_t cp) {
  if (cp >= 0x20 && cp <= 0x7E)
    return kAscii[cp - 0x20];
  // Map common Latin-1 / UTF umlauts onto nearby ASCII for DE/FR menus.
  switch (cp) {
    case 0xC4: case 0xE4: return kAscii['A' - 0x20];  // Ä ä → A shape
    case 0xD6: case 0xF6: return kAscii['O' - 0x20];
    case 0xDC: case 0xFC: return kAscii['U' - 0x20];
    case 0xDF: return kAscii['B' - 0x20];             // ß
    case 0xC9: case 0xE9: return kAscii['E' - 0x20];  // É é
    case 0xC8: case 0xE8: return kAscii['E' - 0x20];
    case 0xE0: case 0xE1: return kAscii['A' - 0x20];
    case 0xF1: return kAscii['N' - 0x20];
    case 0xA0: return kSpace.data();
    default: return nullptr;
  }
}

std::uint32_t nextCodepoint(std::string_view& s) {
  if (s.empty())
    return 0;
  const auto b0 = static_cast<unsigned char>(s[0]);
  if (b0 < 0x80) {
    s.remove_prefix(1);
    return b0;
  }
  if ((b0 & 0xE0) == 0xC0 && s.size() >= 2) {
    const auto b1 = static_cast<unsigned char>(s[1]);
    s.remove_prefix(2);
    return ((b0 & 0x1F) << 6) | (b1 & 0x3F);
  }
  if ((b0 & 0xF0) == 0xE0 && s.size() >= 3) {
    const auto b1 = static_cast<unsigned char>(s[1]);
    const auto b2 = static_cast<unsigned char>(s[2]);
    s.remove_prefix(3);
    return ((b0 & 0x0F) << 12) | ((b1 & 0x3F) << 6) | (b2 & 0x3F);
  }
  s.remove_prefix(1);
  return '?';
}

void blitGlyph(Image& img, int cellX, int cellY, const std::uint8_t rows[8]) {
  for (int y = 0; y < 8; ++y) {
    const std::uint8_t row = rows[y];
    for (int x = 0; x < 8; ++x) {
      const bool on = (row & (1u << x)) != 0;
      const int px = cellX * 8 + x;
      const int py = cellY * 8 + y;
      std::uint8_t* p = img.rgba.data() + (static_cast<std::size_t>(py) * img.width + px) * 4;
      p[0] = 255;
      p[1] = 255;
      p[2] = 255;
      p[3] = on ? 255 : 0;
    }
  }
}

