Font Font::make() {
  Font f;
  f.atlasW = kCols * kGlyph;
  f.atlasH = kRows * kGlyph;
  f.atlas.width = f.atlasW;
  f.atlas.height = f.atlasH;
  f.atlas.rgba.assign(static_cast<std::size_t>(f.atlasW) * f.atlasH * 4, 0);

  for (int cp = 0; cp < 256; ++cp) {
    const std::uint8_t* bits = glyphBits(static_cast<std::uint32_t>(cp));
    if (!bits)
      bits = kSpace.data();
    blitGlyph(f.atlas, cp % kCols, cp / kCols, bits);
  }
  // Place umlaut remaps into their Latin-1 cells so glyphRect can use cp directly.
  for (std::uint32_t cp : {0xC4u, 0xE4u, 0xD6u, 0xF6u, 0xDCu, 0xFCu, 0xDFu, 0xC9u, 0xE9u,
                            0xC8u, 0xE8u, 0xE0u, 0xE1u, 0xF1u}) {
    if (const std::uint8_t* bits = glyphBits(cp))
      blitGlyph(f.atlas, static_cast<int>(cp % kCols), static_cast<int>(cp / kCols), bits);
  }
  return f;
}

bool Font::glyphRect(std::uint32_t cp, int& sx, int& sy) const {
  if (cp == '\n' || cp == '\r' || cp == '^')
    return false;
  std::uint32_t cell = cp <= 255 ? cp : static_cast<std::uint32_t>('?');
  sx = static_cast<int>((cell % static_cast<std::uint32_t>(kCols)) * kGlyph);
  sy = static_cast<int>((cell / static_cast<std::uint32_t>(kCols)) * kGlyph);
  return true;
}

int Font::measure(std::string_view utf8, float scale) const {
  int w = 0;
  while (!utf8.empty()) {
    const std::uint32_t cp = nextCodepoint(utf8);
    if (cp == '^' || cp == '\n')
      break;
    if (cp == 0)
      break;
    w += static_cast<int>(kGlyph * scale);
  }
  return w;
}

